function gearPath() {
  const cx = 24, cy = 24, teeth = 8, ro = 17, ri = 13;
  const pts = [];
  for (let i = 0; i < teeth; i++) {
    const a = (i / teeth) * Math.PI * 2, w = Math.PI / teeth;
    for (const [ang, r] of [[a - w * 0.55, ri], [a - w * 0.35, ro], [a + w * 0.35, ro], [a + w * 0.55, ri]]) {
      pts.push(`${(cx + r * Math.cos(ang)).toFixed(1)} ${(cy + r * Math.sin(ang)).toFixed(1)}`);
    }
  }
  return `<path d="M${pts.join('L')}Z"/><circle cx="24" cy="24" r="5.5"/>`;
}
function starPath() {
  const pts = [];
  for (let i = 0; i < 10; i++) {
    const a = -Math.PI / 2 + (i * Math.PI) / 5, r = i % 2 ? 7.6 : 18;
    pts.push(`${(24 + r * Math.cos(a)).toFixed(1)} ${(25.5 + r * Math.sin(a)).toFixed(1)}`);
  }
  return `<path d="M${pts.join('L')}Z"/>`;
}
function wheelPath() {
  let s = '<circle cx="24" cy="24" r="17"/><circle cx="24" cy="24" r="12"/><circle cx="24" cy="24" r="3.5"/><path d="';
  for (let i = 0; i < 5; i++) {
    const a = -Math.PI / 2 + (i * 2 * Math.PI) / 5;
    s += `M${(24 + 3.5 * Math.cos(a)).toFixed(1)} ${(24 + 3.5 * Math.sin(a)).toFixed(1)}L${(24 + 12 * Math.cos(a)).toFixed(1)} ${(24 + 12 * Math.sin(a)).toFixed(1)}`;
  }
  return s + '"/>';
}
