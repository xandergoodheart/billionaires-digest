// Emblem cards: a designed avatar with no face for everyone who has no painted portrait yet.
// Usage: node scripts/build-emblems.mjs            (from the repo root)
//        node scripts/build-emblems.mjs --prune    (also delete emblem SVGs nobody needs any more)
//
// People = data/people/index.json + data/ceos/index.json. Anyone whose slug has no painted portrait
// (a P['slug'] entry in assets/v2/portraits.js outside the generated block, with its image file on disk)
// gets assets/portraits/emblem/<slug>.svg: a radial gradient in their sector colour, a faint engraved
// guilloche, their initials as glyph paths (Barlow Condensed ExtraBold, so no webfont is needed), a small
// industry line icon (drawn here, no logos or brand marks) and a gold ring. The <title> is the person's name.
// The SVGs are registered in assets/v2/portraits.js between "// emblems:start" and "// emblems:end";
// re-running rewrites that block, so a person drops out of it once a painted portrait is added.
// Output is deterministic: files are rewritten only when their content changes.

