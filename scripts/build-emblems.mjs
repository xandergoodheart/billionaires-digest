// ---------- colours: the site's sector plate tokens (assets/v2/ui.css), deepened ----------
export function slugOf(s) {
  return String(s ?? '').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9]+/g, ' ').trim().replace(/ /g, '-');
}
function readPlates() {
  const css = readFileSync(join(ROOT, 'assets/v2/ui.css'), 'utf8');
  const plates = {};
  for (const m of css.matchAll(/\.v2-av\[data-sector="([a-z-]+)"\]\s*\{\s*--plate:\s*(#[0-9A-Fa-f]{6})\s*;/g)) plates[m[1]] = m[2];
  return plates;
}
function hexToHsl(hex) {
  const n = parseInt(hex.slice(1), 16), r = (n >> 16 & 255) / 255, g = (n >> 8 & 255) / 255, b = (n & 255) / 255;
  const mx = Math.max(r, g, b), mn = Math.min(r, g, b), l = (mx + mn) / 2, d = mx - mn;
  if (!d) return [0, 0, l];
  const s = d / (1 - Math.abs(2 * l - 1));
  let h = mx === r ? ((g - b) / d) % 6 : mx === g ? (b - r) / d + 2 : (r - g) / d + 4;
  h = (h * 60 + 360) % 360;
  return [h, s, l];
}
function hsl(h, s, l) {
  const c = (1 - Math.abs(2 * l - 1)) * s, x = c * (1 - Math.abs((h / 60) % 2 - 1)), m = l - c / 2;
  const [r, g, b] = h < 60 ? [c, x, 0] : h < 120 ? [x, c, 0] : h < 180 ? [0, c, x] : h < 240 ? [0, x, c] : h < 300 ? [x, 0, c] : [c, 0, x];
  return '#' + [r, g, b].map(v => Math.round((v + m) * 255).toString(16).padStart(2, '0')).join('').toUpperCase();
}
export function paletteFor(plateHex) {
  const [h, s] = hexToHsl(plateHex || '#E6E9ED');
  const sat = Math.min(0.6, Math.max(0.22, 0.15 + s * 0.8));
  return { hi: hsl(h, sat, 0.44), mid: hsl(h, sat, 0.27), edge: hsl(h, sat * 0.85, 0.11) };
}

// ---------- initials as glyph paths ----------
export function initialsOf(name, slug) {
  if (INITIALS_OVERRIDES[slug]) return INITIALS_OVERRIDES[slug];
  // same rule as BD.initials in assets/common.js: first + last word
  const ws = String(name || '').replace(/\s*&\s*family\s*$/i, '').split(/\s+/).filter(x => /^[A-Za-zÀ-ɏ]/.test(x));
  if (!ws.length) return '';
  return (ws[0].charAt(0) + (ws.length > 1 ? ws[ws.length - 1].charAt(0) : '')).normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase();
}
let fontData = null;
async function glyphPath(text) {
  fontData ??= readFileSync(FONT);
  const svg = await satori(
    { type: 'div', props: { style: { display: 'flex', width: 512, height: 512, alignItems: 'center', justifyContent: 'center', fontSize: 250, letterSpacing: 4, color: '#fff', fontFamily: 'Barlow Condensed' }, children: text } },
    { width: 512, height: 512, fonts: [{ name: 'Barlow Condensed', data: fontData, weight: 800, style: 'normal' }] }
  );
  const ds = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map(m => m[1]);
  if (!ds.length) throw new Error(`no glyph paths for "${text}"`);
  // drop zero-length repeats like "L1 2L1 2" that satori emits between segments
  return ds.join('').replace(/L(-?[\d.]+ -?[\d.]+)L\1(?=[A-Za-z])/g, 'L$1');
}

// ---------- the card ----------
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
let rosette = null;
function rosetteMarkup() {
  if (rosette) return rosette;
  let s = '<g fill="none" stroke="#fff" stroke-width="1.2" opacity=".09"><ellipse id="e" cx="256" cy="256" rx="214" ry="64"/>';
  for (let i = 1; i < 18; i++) s += `<use href="#e" transform="rotate(${i * 10} 256 256)"/>`;
  s += '<circle cx="256" cy="256" r="150"/><circle cx="256" cy="256" r="64"/></g>';
  return (rosette = s);
}
export async function emblemSvg({ name, slug, plate, icon }) {
  const pal = paletteFor(plate);
  const ini = initialsOf(name, slug);
  const d = ini ? await glyphPath(ini) : '';
  const parts = [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" role="img">`,
    `<title>${esc(name)}</title>`,
    '<defs>',
    `<radialGradient id="g" cx="40%" cy="32%" r="78%"><stop offset="0" stop-color="${pal.hi}"/><stop offset=".55" stop-color="${pal.mid}"/><stop offset="1" stop-color="${pal.edge}"/></radialGradient>`,
    '<linearGradient id="au" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#F4DC9C"/><stop offset=".5" stop-color="#D2A954"/><stop offset="1" stop-color="#9C7330"/></linearGradient>',
    '<pattern id="h" width="7" height="7" patternUnits="userSpaceOnUse" patternTransform="rotate(45)"><path d="M0 0V7" stroke="#fff" stroke-width="1"/></pattern>',
    d ? `<path id="i" d="${d}"/>` : '',
    '</defs>',
    '<rect width="512" height="512" fill="url(#g)"/>',
    '<rect width="512" height="512" fill="url(#h)" opacity=".06"/>',
    rosetteMarkup(),
    d ? '<g transform="translate(0 -36)"><use href="#i" transform="translate(0 7)" fill="#000" opacity=".35"/><use href="#i" fill="#FBF5E6"/></g>' : '',
    `<g transform="translate(210.4 356) scale(1.9)" fill="none" stroke="url(#au)" stroke-width="2.6" stroke-linecap="round" stroke-linejoin="round">${ICONS[icon] || ICONS.other}</g>`,
    '<circle cx="256" cy="256" r="238" fill="none" stroke="url(#au)" stroke-width="7"/>',
    '<circle cx="256" cy="256" r="224" fill="none" stroke="#E7C77E" stroke-width="1.5" opacity=".55"/>',
    '</svg>\n'
  ];
  return parts.join('');
}

// ---------- who needs one ----------
function readJson(p) { return JSON.parse(readFileSync(join(ROOT, p), 'utf8')); }
export function stripBlock(js) {
  const a = js.indexOf(START), b = js.indexOf(END);
  if (a < 0 || b < 0) return { before: js, after: '', had: false };
  return { before: js.slice(0, a), after: js.slice(b + END.length).replace(/^\n/, ''), had: true };
}
function paintedSlugs(js) {
  const { before, after } = stripBlock(js);
  const out = new Set();
  for (const m of (before + after).matchAll(/P\['([a-z0-9-]+)'\]\s*=\s*\{\s*img:\s*'([^']+)'/g)) {
    if (existsSync(join(ROOT, m[2].replace(/^\//, '')))) out.add(m[1]);
  }
  return out;
}
export function emblemPeople() {
  const js = readFileSync(PORTRAITS_JS, 'utf8');
  const painted = paintedSlugs(js);
  const plates = readPlates();
  const seen = new Set(), out = [];
  const pool = [...(readJson('data/people/index.json').people || []), ...(readJson('data/ceos/index.json').people || [])];
  for (const p of pool) {
    if (!p || !SLUG_RE.test(p.slug || '') || typeof p.name !== 'string' || seen.has(p.slug)) continue;
    seen.add(p.slug);
    if (painted.has(p.slug)) continue;
    const sec = slugOf(p.sector || 'Other');
    const icon = ICON_OVERRIDES[p.slug] || SECTOR_ICON[sec] || 'other';
    out.push({ slug: p.slug, name: p.name.replace(/\s*&\s*family\s*$/i, ' & family'), sector: p.sector || 'Other', source: p.source || p.company || '', plate: plates[sec] || plates.other, icon });
  }
  return out;
}

function writeIfChanged(file, text) {
  if (existsSync(file) && readFileSync(file, 'utf8') === text) return false;
  writeFileSync(file, text);
  return true;
}

export async function buildEmblems({ prune = false } = {}) {
  const people = emblemPeople();
  mkdirSync(OUT_DIR, { recursive: true });
  let written = 0, maxBytes = 0;
  for (const p of people) {
    const svg = await emblemSvg(p);
    maxBytes = Math.max(maxBytes, Buffer.byteLength(svg));
    if (writeIfChanged(join(OUT_DIR, `${p.slug}.svg`), svg)) written++;
  }
  // registry block in assets/v2/portraits.js, just above the silhouette fallback
  const js = readFileSync(PORTRAITS_JS, 'utf8');
  const { before, after, had } = stripBlock(js);
  const block = [START, '  // emblem cards: no face, sector colour + initials + industry icon, for people without a painted portrait'];
  for (const p of people) block.push(`  P['${p.slug}'] = { img: '/assets/portraits/emblem/${p.slug}.svg', emblem: true };`);
  block.push(END, '');
  let next;
  if (had) next = before + block.join('\n') + after;
  else {
    const anchor = js.indexOf('  // people without a portrait:');
    if (anchor < 0) throw new Error('portraits.js: fallback comment not found; cannot place the emblem block');
    next = js.slice(0, anchor) + block.join('\n') + js.slice(anchor);
  }
  writeIfChanged(PORTRAITS_JS, next);
  // emblem files nobody needs any more (a painted portrait arrived): listed, deleted only with --prune
  const keep = new Set(people.map(p => `${p.slug}.svg`));
  const stale = readdirSync(OUT_DIR).filter(f => f.endsWith('.svg') && !keep.has(f));
  if (prune) for (const f of stale) unlinkSync(join(OUT_DIR, f));
  return { people, written, maxBytes, stale, pruned: prune };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const r = await buildEmblems({ prune: process.argv.includes('--prune') });
  console.log(`emblems: ${r.people.length} people, ${r.written} file(s) written, largest ${r.maxBytes} bytes`);
  for (const p of r.people) console.log(`  ${p.slug.padEnd(36)} ${initialsOf(p.name, p.slug).padEnd(3)} ${p.icon.padEnd(11)} ${p.sector} | ${p.source}`);
  if (r.stale.length) console.log(`${r.pruned ? 'deleted' : 'not needed any more (run with --prune to delete)'}: ${r.stale.join(', ')}`);
}
